const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');
app.setPath('userData', path.join(require('node:os').tmpdir(), 'voice-workspace-smoke-' + process.pid));
const created = new Promise(resolve => app.once('browser-window-created', (_, win) => resolve(win)));
const launcher = require('./open-code.cjs');
let openedContent = null;
launcher.installedApps = async () => ({cursor:'/Applications/Cursor.app',matlab:null});
launcher.openMac = async (appPath,filePath) => {if(appPath!=='/Applications/Cursor.app')throw Error('Wrong app');openedContent=await fs.readFile(filePath,'utf8');if(!/^[A-Za-z][A-Za-z0-9_]*$/.test(path.basename(filePath,path.extname(filePath))))throw Error('Invalid MATLAB-compatible filename');if(!filePath.endsWith('.py'))throw Error('Wrong extension');};
require('./main.cjs');
created.then(async win => {
  await new Promise(resolve => win.webContents.once('did-finish-load', resolve));
  const run = code => win.webContents.executeJavaScript(code);
  const wait = async expr => { for(let i=0;i<200;i++){if(await run(expr))return;await new Promise(r=>setTimeout(r,50));}throw Error('Timed out: '+expr); };
  try {
    await wait("!document.querySelector('.demo').disabled");
    await run("document.querySelector('.demo').click()");
    await wait("document.querySelector('.paper h1')?.textContent === 'Ideas deserve a voice' && !document.querySelector('.demo').disabled");
    const shot = await win.webContents.capturePage(); await fs.writeFile(path.join(__dirname, '../preview.png'),shot.toPNG());
    await run("[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Undo')).click()");
    await wait("document.querySelector('.source textarea').value === ''");
    await run("document.querySelector('.segmented button:last-child').click()");
    await wait("document.querySelector('.segmented button:last-child').classList.contains('selected')");
    await run("document.querySelector('.demo').click()");
    await wait("document.querySelector('.source textarea').value.includes('summarize_folder') && !!document.querySelector('.launch-panel') && !document.querySelector('.demo').disabled");
    await run("[...document.querySelectorAll('.launch-buttons button')].find(button=>button.textContent.includes('Cursor')).click()");
    await wait("document.querySelector('footer').textContent.includes('opened it in Cursor')");
    if(!openedContent?.includes('summarize_folder'))throw Error('Latest generated source was not handed off');
    await run("document.querySelector('.segmented button:first-child').click()");
    await wait("document.querySelector('.source textarea').value === '' && !!document.querySelector('.paper')");
    await run("document.querySelector('.demo').click()");
    await wait("document.querySelector('.paper h1')?.textContent === 'Ideas deserve a voice' && !document.querySelector('.demo').disabled");
    await run("document.querySelector('.segmented button:last-child').click()");
    await wait("document.querySelector('.source textarea').value.includes('summarize_folder')");
    await wait("window.desktop.load().then(draft=>draft.workspaces.code.content.includes('summarize_folder') && draft.workspaces.document.content.includes('Ideas deserve a voice') && draft.mode === 'code')");
    win.webContents.reload();
    await new Promise(resolve=>win.webContents.once('did-finish-load',resolve));
    await wait("document.querySelector('.source textarea').value.includes('summarize_folder') && !document.querySelector('.demo').disabled");
    await run("document.querySelector('.segmented button:first-child').click()");
    await wait("document.querySelector('.paper h1')?.textContent === 'Ideas deserve a voice'");
    await run("[...document.querySelectorAll('button')].find(button=>button.textContent.includes('Undo')).click()");
    await wait("document.querySelector('.source textarea').value === ''");
    await run("document.querySelector('.segmented button:last-child').click()");
    await wait("document.querySelector('.source textarea').value.includes('summarize_folder')");
    await run("document.querySelector('.header-actions button').click()");
    await wait("!!document.querySelector('input[type=password]')");
    await run("document.querySelector('.settings button[type=button]').click();const select=document.querySelector('.model-picker select');select.value='gemini-3.5-flash-lite';select.dispatchEvent(new Event('change',{bubbles:true}))");
    await wait("document.querySelector('.model-picker select').value === 'gemini-3.5-flash-lite' && document.querySelector('footer').textContent.includes('Model changed')");
    if (!(await run("window.desktop.settings().then(value => value.model === 'gemini-3.5-flash-lite')"))) throw Error('Model selection was not saved');
    console.log('PASS: launch, document streaming, Markdown preview, Undo, code preview, settings');
    app.exit(0);
  } catch(error) { console.error(error.message); console.error(await run("JSON.stringify({status:document.querySelector('footer').innerText,source:document.querySelector('.source textarea').value,preview:document.querySelector('.paper').innerText,mode:document.querySelector('.selected').textContent})")); app.exit(1); }
});
